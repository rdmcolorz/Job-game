// Simple matching: score jobs based on skill overlap and preference match
export function scoreJobForUser(job, userProfile) {
  if (!userProfile) return 0;
  let score = 0;

  // Skill match: +25 points per matching skill
  const userSkills = (userProfile.skills || []).map(s => s.toLowerCase());
  const jobSkills = (job.skills || []).map(s => s.toLowerCase());
  const matchingSkills = jobSkills.filter(s => userSkills.includes(s));
  score += matchingSkills.length * 25;

  // Job type preference match: +20 points
  if (userProfile.preferredJobType && job.type === userProfile.preferredJobType) {
    score += 20;
  }

  // Location preference match: +15 points
  if (userProfile.preferredLocation &&
      job.location.toLowerCase().includes(userProfile.preferredLocation.toLowerCase())) {
    score += 15;
  }

  // Salary range overlap: +10 points
  if (userProfile.salaryRange?.min && job.salaryMax >= userProfile.salaryRange.min) {
    score += 10;
  }

  return score;
}
